"""CFD (Cutting Frequency Determination) off-target score.

Implements the CFD specificity score of Doench et al., Nat. Biotechnol. 2016
(doi:10.1038/nbt.3437): an estimate, in [0, 1], of how efficiently SpCas9
cleaves a mismatched/bulged site relative to a perfect-match on-target. CFD is
the product of one penalty per spacer position times a single PAM penalty. The
penalties are the published lookup values, loaded from
``cfd_mismatch_scores.json`` + ``cfd_pam_scores.json`` (generated by
``scripts/generate_cfd_tables.py``).

Scoring rules (per Doench 2016, reproduced exactly):

  * The spacer and the protospacer are compared as RNA (every ``T`` read as
    ``U``) over the aligned positions ``1..len``.
  * A position where the two agree contributes a factor of ``1.0``.
  * A position where they differ contributes the tabulated penalty keyed by
    ``r<spacer base>:d<complement of the protospacer base>,<position>``. A key
    that is absent from the table -- e.g. a gap at the PAM-distal first position
    -- contributes ``1.0`` (no penalty on record for it).
  * A protospacer base with no Watson-Crick complement (an ``N`` or other
    ambiguous letter) makes the whole score ``0.0``.
  * The PAM contributes ``pam_table.get(pam, 0.0)`` -- a non-canonical or
    unrecognised PAM contributes ``0.0`` rather than raising.

This scorer is alignment-agnostic: it scores a guide/protospacer pair that the
caller has already laid out over the spacer positions plus a trailing PAM. A
caller that models a DNA bulge presents the trimmed, 20-nt-wide alignment; this
module never repositions or trims bases itself.
"""
import json
import os

_DIR = os.path.dirname(os.path.abspath(__file__))
_MISMATCH_TABLE_PATH = os.path.join(_DIR, "cfd_mismatch_scores.json")
_PAM_TABLE_PATH = os.path.join(_DIR, "cfd_pam_scores.json")

# Watson-Crick complement used to build the "d<base>" half of a penalty key.
# ``U`` collapses to ``A`` (the spacer/protospacer are read as RNA) and a gap
# maps to a gap. Any other letter (``N`` / IUPAC ambiguity) has no entry and
# therefore zeroes the score (see ``position_penalty``).
_COMPLEMENT = {"A": "T", "C": "G", "G": "C", "T": "A", "U": "A", "-": "-"}

_tables_cache = None


def cfd_tables():
    """Return ``(mismatch_penalties, pam_penalties)`` as dicts, loaded once."""
    global _tables_cache
    if _tables_cache is None:
        with open(_MISMATCH_TABLE_PATH) as fh:
            mismatch = json.load(fh)
        with open(_PAM_TABLE_PATH) as fh:
            pam = json.load(fh)
        _tables_cache = (mismatch, pam)
    return _tables_cache


def _as_rna(seq):
    """Read a sequence as RNA by treating every ``T`` as ``U``."""
    return seq.replace("T", "U")


def position_penalty(spacer_base, protospacer_base, position, mismatch_penalties):
    """Per-position CFD factor for one aligned column (bases already RNA-read).

    Returns the factor in [0, 1], or ``None`` to signal that the protospacer
    base is untranslatable and the whole score must collapse to ``0.0``.
    """
    if spacer_base == protospacer_base:
        return 1.0
    complement = _COMPLEMENT.get(protospacer_base)
    if complement is None:
        return None  # ambiguous protospacer base -> caller zeroes the score
    key = "r%s:d%s,%d" % (spacer_base, complement, position)
    return mismatch_penalties.get(key, 1.0)  # absent key (e.g. first-position gap) -> no penalty


def cfd(spacer, protospacer, pam, tables=None):
    """CFD score of a protospacer+PAM against a spacer, all aligned by position.

    ``spacer`` and ``protospacer`` are the aligned sequences over the spacer
    positions (equal length); ``pam`` is the PAM read for the lookup. Pass
    ``tables`` (from :func:`cfd_tables`) to avoid re-loading on hot paths.
    """
    mismatch_penalties, pam_penalties = tables if tables is not None else cfd_tables()
    spacer = _as_rna(spacer)
    protospacer = _as_rna(protospacer)
    product = 1.0
    for offset, (spacer_base, protospacer_base) in enumerate(zip(spacer, protospacer)):
        factor = position_penalty(spacer_base, protospacer_base, offset + 1, mismatch_penalties)
        if factor is None:
            return 0.0
        product *= factor
    return product * pam_penalties.get(pam, 0.0)
